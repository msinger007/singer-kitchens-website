#!/usr/bin/env python3
"""Write netlify.toml (build settings, headers, 301 redirects) from the WordPress export.
Run after tools/convert_wp.py:  python3 tools/make_netlify_toml.py
"""
import glob, json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import wp_export as W

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
E = W.load(sorted(glob.glob(os.path.join(ROOT, 'source', 'singerkitchens.WordPress.*.xml')))[-1])
items = E['items']
pub = [i for i in items if i['status'] == 'publish' and i['type'] in ('page', 'post', 'service-area')]
live = {W.path_of(i) for i in pub}
by_id = {i['id']: i for i in items}
rules = []  # (from, to, query)
seen = set()

def add(frm, to, query=None, force=False):
    key = (frm, json.dumps(query, sort_keys=True))
    if key in seen or frm == to:
        return
    seen.add(key)
    rules.append((frm, to, query, force))

# Site-plan strays
add('/home', '/'); add('/home/', '/')
# /kitchen-design/ is published as its own page (not redirected to /kitchens/)
# Dead internal links found in old content (pages not in the export) -> closest live page
for frm, to in [('/locations/', '/showrooms/'), ('/kitchen-remodeling/', '/remodeling/'), ('/closet-renovation/', '/closets/'),
                ('/small-kitchens/', '/small-kitchen-remodeling/'), ('/murphy-beds/', '/closets/'),
                ('/learn-the-secret-to-designing-a-modern-kitchen-your-family-will-love-for-free/', '/kitchen-design-secrets/')]:
    add(frm, to); add(frm.rstrip('/'), to)
# Blog pagination: Kitchen Stories pages keep /blog/2/ etc.; WordPress-style /blog/page/2/ also works
add('/blog/page/:n', '/blog/:n/'); add('/blog/page/:n/', '/blog/:n/')
# WordPress-only paths
for p in ('category', 'tag', 'author'):
    add('/%s/*' % p, '/blog/')
add('/feed', '/blog/'); add('/feed/', '/blog/'); add('/comments/feed/', '/blog/'); add('/blog/feed/', '/blog/')
for path in sorted(live):
    if path != '/':
        add(path + 'feed/', path)
for y in range(2017, 2027):
    add('/%d/*' % y, '/blog/')
# Yoast redirects recorded on items (e.g. /service-area/mandeville-la -> /service-area/mandeville/)
for i in items:
    info = W.php_unserialize(i['meta'].get('_yoast_post_redirect_info'))
    if isinstance(info, dict) and info.get('origin') and info.get('target'):
        o = '/' + info['origin'].strip('/') + '/'
        t = '/' + info['target'].strip('/') + '/'
        if o not in live:
            add(o.rstrip('/'), t); add(o, t)
# Service-area links written without the /service-area/ prefix
for path in sorted(live):
    if path.startswith('/service-area/'):
        short = path[len('/service-area'):]
        if short not in live and short.count('/') > 2:
            add(short, path); add(short.rstrip('/'), path)
# Attachment pages -> parent post/page
for a in items:
    if a['type'] != 'attachment':
        continue
    parent = by_id.get(a['parent'])
    target = W.path_of(parent) if parent and parent['status'] == 'publish' and parent['type'] in ('page', 'post', 'service-area') else '/blog/'
    add('/', target, {'attachment_id': str(a['id'])})
    ap = W.path_of(a)
    if ap not in live and ap not in ('/', ''):
        if not ap.startswith('/?'):
            add(ap, target)
add('/', '/blog/', {'attachment_id': ':id'})
# Original upload URLs -> converted WebP (images people may have linked from outside)
manifest = json.load(open(os.path.join(ROOT, 'src', '_data', 'generated', 'images.json')))
for orig, v in sorted(manifest.items()):
    if '#' in orig:
        continue
    src = '/wp-content/uploads/' + orig
    if not os.path.exists(os.path.join(ROOT, 'src', 'wp-content', 'uploads', orig)):
        add(src, v['src'])

def q(s):
    return json.dumps(s)

out = ['# Generated by tools/make_netlify_toml.py. Edit that script, not this file.', '',
       '[build]', '  command = "npm run build"', '  publish = "_site"', '',
       '[build.environment]', '  NODE_VERSION = "22"', '',
       '[[headers]]', '  for = "/*"', '  [headers.values]', '    X-Content-Type-Options = "nosniff"',
       '    Referrer-Policy = "strict-origin-when-cross-origin"', '    X-Frame-Options = "SAMEORIGIN"', '',
       '[[headers]]', '  for = "/images/*"', '  [headers.values]', '    Cache-Control = "public, max-age=31536000"', '',
       '[[headers]]', '  for = "/assets/*"', '  [headers.values]', '    Cache-Control = "public, max-age=604800"', '']
for frm, to, query, force in rules:
    out += ['[[redirects]]', '  from = %s' % q(frm), '  to = %s' % q(to), '  status = 301']
    if query:
        out.append('  query = {%s}' % ', '.join('%s = %s' % (k, q(v)) for k, v in query.items()))
    out.append('')
open(os.path.join(ROOT, 'netlify.toml'), 'w').write('\n'.join(out))
print(len(rules), 'redirect rules')
